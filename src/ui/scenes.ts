/**
 * Задник игры — ровная заливка, которая меняется каждые десять уровней.
 *
 * Смена картинки на десятом уровне — классика жанра и единственная награда,
 * которую видно сразу и целиком: сундук сыплет монеты, а мир за блоком в тот же
 * момент становится другим. Поэтому шаг смены намеренно совпадает с шагом
 * сундука (CHEST_GOAL в storage.ts), и ломать это врозь нельзя.
 *
 * Пока настоящих пейзажей нет, вместо них спокойный сине-зелёный градиент:
 * рисованный вектором пейзаж честно показывал, что он вектор, и спорил
 * с плитками за внимание. Ровный фон не спорит ни с чем, а глава всё равно
 * читается — у каждой свой оттенок.
 *
 * Точка замены ровно одна: SCENES отдаёт готовый background-image. Появятся
 * растровые пейзажи — вместо вызова fill() туда ляжет `data:image/webp;base64,…`,
 * и остальной код об этом не узнает.
 */
export interface Scene {
  /** Имя сцены латиницей: она нигде не показывается, а русская строка в src/ui
      нарушила бы правило «всё языковое живёт в пакете языка». */
  id: string;
  /** Готовый background-image. */
  image: string;
}

/**
 * Заливка главы: градиент сверху вниз плюс мягкий свет в верхней трети —
 * совсем ровный цвет на большом экране выглядит браком печати, а не фоном.
 */
const fill = (top: string, bottom: string): string =>
  `radial-gradient(90% 55% at 50% 22%, rgba(255, 255, 255, 0.1), rgba(255, 255, 255, 0) 70%), ` +
  `linear-gradient(180deg, ${top} 0%, ${bottom} 100%)`;

export const SCENES: Scene[] = [
  { id: 'teal', image: fill('#2f8188', '#1c5a62') },
  { id: 'jade', image: fill('#2c8279', '#1a5e57') },
  { id: 'lagoon', image: fill('#2f7691', '#1b5266') },
  { id: 'moss', image: fill('#358780', '#1f615c') },
  { id: 'deep', image: fill('#2a6d84', '#184c5e') },
];

/** Сколько уровней держится один фон. Тот же шаг, что у сундука. */
export const SCENE_SPAN = 10;

/** Какой фон стоит за уровнем. Когда оттенки кончаются, они идут по кругу. */
export function sceneFor(levelIndex: number): Scene {
  const chapter = Math.floor(Math.max(0, levelIndex - 1) / SCENE_SPAN);
  return SCENES[chapter % SCENES.length];
}
